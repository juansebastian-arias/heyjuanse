/**
 * Message templates for synthetic inbound leads, each annotated with the signals it
 * actually contains.
 *
 * The annotations are the ground truth for the AI extraction evaluation. They follow the
 * definitions in `core/ai/prompt.ts`; when a message is genuinely ambiguous, `accept`
 * lists the other answers a careful human reviewer would also accept.
 *
 * Templates were written for this project (with AI assistance) and reviewed by hand.
 * Placeholders such as {company} are filled by the generator; none of them changes the
 * annotated signals.
 */
import type {
  AcceptableAlternatives,
  Budget,
  BuyerStage,
  Intent,
  Language,
  MessageSignals,
  NextStep,
  PainPoint,
  Persona,
  Timeline,
} from "../model";

/** Where the text comes from. Booth, webinar and referral notes are written by other people. */
export type Channel = "form" | "booth" | "webinar" | "referral";

export interface MessageTemplate {
  id: string;
  channel: Channel;
  persona: Persona;
  /** For buyers: the stages this template fits. Empty means any stage. */
  stages: BuyerStage[];
  /** For buyers: true if written by someone with a real need, false if not, null if either. */
  need: boolean | null;
  lang: "en" | "es" | "pt";
  text: string;
  signals: MessageSignals;
  accept: AcceptableAlternatives;
}

interface Spec {
  id: string;
  channel?: Channel;
  persona?: Persona;
  stages?: BuyerStage[];
  need?: boolean | null;
  lang?: "en" | "es" | "pt";
  text: string;
  intent: Intent;
  timeline?: Timeline;
  budget?: Budget;
  next?: NextStep;
  pains?: PainPoint[];
  injection?: boolean;
  language?: Language;
  accept?: AcceptableAlternatives;
}

function t(spec: Spec): MessageTemplate {
  const lang = spec.lang ?? "en";
  return {
    id: spec.id,
    channel: spec.channel ?? "form",
    persona: spec.persona ?? "buyer",
    stages: spec.stages ?? [],
    need: spec.need ?? null,
    lang,
    text: spec.text,
    signals: {
      intent: spec.intent,
      timeline: spec.timeline ?? "not_stated",
      budget: spec.budget ?? "not_mentioned",
      nextStep: spec.next ?? "none",
      painPoints: spec.pains ?? [],
      language: spec.language ?? lang,
      injection: spec.injection ?? false,
    },
    accept: spec.accept ?? {},
  };
}

